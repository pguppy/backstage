def main():
    config = FEATURE_CONFIG
    root = find_project_root()
    yarn = find_yarn()
    plugin_id = config['id']
    
    print(f"Project root: {root}")
    print(f"Yarn: {yarn}")
    print(f"Feature: {config['name']} ({plugin_id})")
    print(f"Packages: {config['packages']}")
    print()
    
    # Map package types to yarn new template names
    template_map = {
        'common': 'plugin-common-library',
        'node': 'plugin-node-library',
        'backend': 'backend-plugin',
        'react': 'plugin-web-library',
        'frontend': 'frontend-plugin',
    }
    
    created_packages = []
    
    # Step 1: Scaffold all packages
    for pkg_type in config['packages']:
        if pkg_type not in template_map:
            print(f"SKIP: Unknown package type '{pkg_type}'")
            continue
        
        template = template_map[pkg_type]
        print(f"Scaffolding {pkg_type} package (template: {template})...")
        run_yarn_new(template, plugin_id)
        
        pkg_dir = get_package_dir('frontend' if pkg_type == 'frontend' else pkg_type, plugin_id)
        if os.path.isdir(pkg_dir):
            created_packages.append((pkg_type, pkg_dir))
            print(f"  ✓ Created: {pkg_dir}")
        else:
            print(f"  ✗ Failed to create package")
    
    print()
    
    # Step 2: Clean demo files + fill templates + update package.json
    for pkg_type, pkg_dir in created_packages:
        print(f"Processing {pkg_type} package...")
        
        # Clean demo files
        clean_demo_files(pkg_dir, pkg_type)
        
        # Fill templates
        if pkg_type == 'common':
            content = replace_placeholders(get_common_types_template(), config)
            write_file(os.path.join(pkg_dir, 'src', 'types.ts'), content)
            write_file(os.path.join(pkg_dir, 'src', 'index.ts'), get_common_index_template())
            
        elif pkg_type == 'backend':
            for fname, template_fn in [
                ('plugin.ts', get_backend_plugin_template),
                ('router.ts', get_backend_router_template),
                ('index.ts', get_backend_index_template),
            ]:
                content = replace_placeholders(template_fn(), config)
                write_file(os.path.join(pkg_dir, 'src', fname), content)
            
        elif pkg_type == 'frontend':
            os.makedirs(os.path.join(pkg_dir, 'src', 'components'), exist_ok=True)
            for fname, template_fn in [
                ('plugin.ts', get_frontend_plugin_template),
                ('index.ts', get_frontend_index_template),
            ]:
                content = replace_placeholders(template_fn(), config)
                write_file(os.path.join(pkg_dir, 'src', fname), content)
        
        # Update package.json
        update_package_json(pkg_dir, plugin_id, config['pluginVar'],
                          is_frontend=(pkg_type == 'frontend'),
                          is_backend=(pkg_type == 'backend'))
        
        print(f"  ✓ Templates filled, package.json updated")
    
    print()
    print("=" * 60)
    print("SCAFFOLDING COMPLETE")
    print("=" * 60)
    print()
    print("Next steps:")
    print(f"  1. Add to packages/backend/src/index.ts:")
    print(f"     backend.add(import('@backstage/plugin-{plugin_id}-backend'));")
    print(f"  2. Feature discovery handles frontend automatically")
    print(f"     (app.packages: all in app-config.yaml)")
    print(f"  3. yarn tsc  — verify types")
    print(f"  4. yarn lint --fix  — fix lint issues")
    print(f"  5. yarn changeset  — create changeset")
    print()
    print("Related skills:")
    print("  - backstage-backend-api    → fill in router.ts")
    print("  - backstage-client-api     → fill in API client")
    print("  - backstage-auth-permissions → add auth checks")
    print("  - backstage-ui-components  → build UI")
    print("  - backstage-catalog-system → entity page integration")
    print("  - backstage-testing        → add tests")

if __name__ == '__main__':
    main()
