def find_project_root():
    """Find the Backstage monorepo root."""
    cwd = os.getcwd()
    for _ in range(10):
        if os.path.exists(os.path.join(cwd, '.yarnrc.yml')):
            return cwd
        cwd = os.path.dirname(cwd)
    raise RuntimeError("Not in a Backstage project (no .yarnrc.yml found)")

def find_yarn():
    """Find yarn executable."""
    root = find_project_root()
    yarn_path = os.path.join(root, '.yarn', 'releases')
    if os.path.isdir(yarn_path):
        for f in os.listdir(yarn_path):
            if f.endswith('.cjs'):
                return f"node {os.path.join(yarn_path, f)}"
    return "yarn"  # fallback to PATH

def run_yarn_new(template_name, plugin_id, module_id=None):
    """Run yarn backstage-cli new non-interactively."""
    root = find_project_root()
    yarn = find_yarn()
    
    cmd = f'cd {root} && echo "" | {yarn} backstage-cli new --select {template_name} --option pluginId={plugin_id}'
    if module_id:
        cmd += f' --option moduleId={module_id}'
    
    result = terminal(cmd, timeout=120, workdir=root)
    if result['exit_code'] != 0:
        print(f"WARNING: yarn new may have had issues:\n{result['output'][-500:]}")
    return result

def get_package_dir(package_type, plugin_id):
    """Get the directory for a package type."""
    root = find_project_root()
    return os.path.join(root, 'plugins', f'{plugin_id}-{package_type}' if package_type != 'frontend' else plugin_id)

def clean_demo_files(pkg_dir, package_type):
    """Remove demo/template files generated by yarn new."""
    removals = {
        'common': [],
        'backend': ['src/services'],
        'frontend': ['src/components/ExampleComponent', 'src/components/ExampleFetchComponent'],
    }
    for removal in removals.get(package_type, []):
        path = os.path.join(pkg_dir, removal)
        terminal(f'rm -rf {path}', workdir=pkg_dir)

def update_package_json(pkg_dir, plugin_id, plugin_var, is_frontend=False, is_backend=False):
    """Add pluginId, pluginPackages, and cross-package dependencies."""
    path = os.path.join(pkg_dir, 'package.json')
    
    # Read current
    content = read_file(path)['content']
    pkg = json.loads(content)
    
    # Add plugin grouping
    if 'backstage' not in pkg:
        pkg['backstage'] = {}
    pkg['backstage']['pluginId'] = plugin_id
    pkg['backstage']['pluginPackages'] = [
        f'@backstage/plugin-{plugin_id}',
        f'@backstage/plugin-{plugin_id}-backend',
        f'@backstage/plugin-{plugin_id}-common',
        f'@backstage/plugin-{plugin_id}-node',
        f'@backstage/plugin-{plugin_id}-react',
    ]
    
    # Add cross-package dependency
    if is_backend or is_frontend:
        common_dep = f'@backstage/plugin-{plugin_id}-common'
        if 'dependencies' not in pkg:
            pkg['dependencies'] = {}
        if common_dep not in pkg['dependencies']:
            pkg['dependencies'][common_dep] = 'workspace:^'
    
    write_file(path, json.dumps(pkg, indent=2) + '\n')

def replace_placeholders(text, config):
    """Replace {{placeholders}} in template text."""
    text = text.replace('{{pluginId}}', config['pluginId'])
    text = text.replace('{{PluginId}}', config['PluginId'])
    text = text.replace('{{pluginVar}}', config['pluginVar'])
    text = text.replace('{{pluginIdCap}}', config['pluginIdCap'])
    return text

